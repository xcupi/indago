func TestWAFAdaptiveBlockStatusesWithoutVendor(t *testing.T) {
	cases := []struct {
		status int
		signal string
		backup bool
	}{
		{403, "http_403_forbidden", false},
		{406, "http_406_not_acceptable", false},
		{418, "http_418_teapot", false},
		{501, "http_501_not_implemented", false},
		{429, "http_429_rate_limited", true},
	}
	for _, tc := range cases {
		t.Run(tc.signal, func(t *testing.T) {
			plan := AnalyzeResponseAdaptation(`<svg onload=indago7>`, 200, `<html>ok</html>`, tc.status, nil, `<html>nope</html>`)
			if !plan.Blocked {
				t.Fatalf("status %d must be a block signal: %+v", tc.status, plan)
			}
			if plan.BlockSignal != tc.signal {
				t.Fatalf("BlockSignal = %q, want %q", plan.BlockSignal, tc.signal)
			}
			if plan.BackoffRequired != tc.backup {
				t.Fatalf("BackoffRequired = %v, want %v", plan.BackoffRequired, tc.backup)
			}
			if tc.backup {
				if len(plan.Tactics) != 0 {
					t.Fatalf("no tactic may be offered while the target is throttling: %v", wafAdaptiveTacticIDs(plan))
				}
				return
			}
			// AGENTS.md §2.2: a 403 stays eligible because a filter rejecting the
			// payload is exactly what the fallback exists for.
			if len(plan.Tactics) == 0 {
				t.Fatalf("a plain 403 should still yield documented shapes: %+v", plan)
			}
			wafAdaptiveRequireSortedAndUnique(t, plan)
		})
	}
}

