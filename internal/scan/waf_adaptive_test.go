// TestWAFAdaptiveTacticsAreBenign is the safety fence: every suggested value is
// a benign canary, never SQL injection, a destructive command, or exfiltration.
func TestWAFAdaptiveTacticsAreBenign(t *testing.T) {
	scenarios := []struct {
		payload string
		body    string
	}{
		{`<script>indago7</script>`, `<div>indago7</div>`},
		{`<svg onload=indago7 onerror=indago7>`, `<svg>indago7</svg>`},
		{`"><svg onload=indago7>`, "\\\"<svg onload=indago7>"},
		{`">{{indago7}}`, `<div>indago7</div>`},
		{`;echo indago7`, `;echoindago7`},
		{`<%= 7*7 %>`, `<%=7*7%>`},
		{`{{7*7}}`, `7*7`},
		{`javascript:indago7`, `indago7`},
		{`<svg onload=indago7>`, `&lt;svg onload=indago7&gt;`},
	}
	var payloads []string
	for _, sc := range scenarios {
		for _, tactic := range wafAdaptivePlan(sc.payload, sc.body).Tactics {
			payloads = append(payloads, tactic.Payload)
		}
	}
	// Include the outright-block shapes too.
	for _, tactic := range adaptWAFBlockTactics("indago7") {
		payloads = append(payloads, tactic.Payload)
	}

	forbidden := []string{
		"union select", "sleep(", "benchmark(", "drop table", "delete from",
		"insert into", " or 1=1", "rm -rf", "mkfs", "shutdown", "curl ",
		"wget ", "nc -", "document.cookie", "fetch(", "xmlhttprequest",
		"http://", "https://", "alert(", "confirm(", "prompt(", "eval(",
	}
	seen := 0
	for _, payload := range payloads {
		if payload == "" {
			continue
		}
		seen++
		lower := strings.ToLower(payload)
		for _, bad := range forbidden {
			if strings.Contains(lower, bad) {
				t.Fatalf("payload %q contains forbidden construct %q", payload, bad)
			}
		}
		if !strings.Contains(lower, "indago") && !strings.Contains(payload, "7*7") {
			t.Fatalf("payload %q carries neither a canary nor a benign arithmetic expression", payload)
		}
	}
	if seen == 0 {
		t.Fatal("no tactics were generated; the fence would be vacuous")
	}
}

