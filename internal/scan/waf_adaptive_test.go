// TestWAFAdaptiveImportsStayPure keeps the analyzer a pure function: stdlib
// only, so it can never grow a network, store, browser or LLM dependency.
func TestWAFAdaptiveImportsStayPure(t *testing.T) {
	file, err := parser.ParseFile(token.NewFileSet(), "waf_adaptive.go", nil, parser.ImportsOnly)
	if err != nil {
		t.Fatalf("parse waf_adaptive.go: %v", err)
	}
	if len(file.Imports) == 0 {
		t.Fatal("no imports parsed; the purity check would be vacuous")
	}
	for _, imp := range file.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(strings.SplitN(path, "/", 2)[0], ".") || strings.HasPrefix(path, "github.com/indago/") {
			t.Fatalf("waf_adaptive.go must stay stdlib-only and pure, found import %q", path)
		}
	}
}

