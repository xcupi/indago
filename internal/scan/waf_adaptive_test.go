// wafAdaptivePlan runs the analyzer with a throw-away baseline: an ordinary 200
// page that reflects nothing.
func wafAdaptivePlan(payload, probeBody string) AdaptationPlan {
	return AnalyzeResponseAdaptation(payload, 200, "<html><body>baseline</body></html>", 200, nil, probeBody)
}

func wafAdaptiveTacticIDs(plan AdaptationPlan) []string {
	ids := make([]string, 0, len(plan.Tactics))
	for _, tactic := range plan.Tactics {
		ids = append(ids, tactic.ID)
	}
	return ids
}

func wafAdaptiveTactic(t *testing.T, plan AdaptationPlan, id string) EvasionTactic {
	t.Helper()
	for _, tactic := range plan.Tactics {
		if tactic.ID == id {
			return tactic
		}
	}
	t.Fatalf("tactic %q missing from plan %v", id, wafAdaptiveTacticIDs(plan))
	return EvasionTactic{}
}

func wafAdaptiveRequireSortedAndUnique(t *testing.T, plan AdaptationPlan) {
	t.Helper()
	seen := map[string]bool{}
	last := 1 << 30
	for _, tactic := range plan.Tactics {
		if tactic.ID == "" {
			t.Fatalf("tactic with empty id: %+v", tactic)
		}
		if seen[tactic.ID] {
			t.Fatalf("duplicate tactic id %q", tactic.ID)
		}
		seen[tactic.ID] = true
		if tactic.Priority > last {
			t.Fatalf("tactics not sorted by descending priority: %v", wafAdaptiveTacticIDs(plan))
		}
		last = tactic.Priority
		if tactic.Payload == "" || tactic.Rationale == "" || tactic.Vector == "" || tactic.Trigger == "" {
			t.Fatalf("tactic %q is missing provenance: %+v", tactic.ID, tactic)
		}
	}
}

