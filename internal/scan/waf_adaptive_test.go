func TestWAFAdaptiveBlocksOnNewBlockStatus(t *testing.T) {
	plan := AnalyzeResponseAdaptation(`<script>indago7</script>`, 200, `<html>ok</html>`, 403,
		map[string]string{"CF-RAY": "8f2c1de5"},
		`<html><title>Attention Required! | Cloudflare</title></html>`)

	if !plan.Blocked {
		t.Fatalf("403 after a 200 baseline must be a block signal: %+v", plan)
	}
	if !plan.StatusChanged || plan.BaselineStatus != 200 || plan.ProbeStatus != 403 {
		t.Fatalf("status bookkeeping wrong: %+v", plan)
	}
	if plan.BlockSignal != "cloudflare_challenge" {
		t.Fatalf("BlockSignal = %q, want cloudflare_challenge", plan.BlockSignal)
	}
	if plan.WAFVendor != "Cloudflare" {
		t.Fatalf("WAFVendor = %q, want Cloudflare", plan.WAFVendor)
	}
	if plan.BackoffRequired {
		t.Fatalf("403 must not demand backoff: %+v", plan)
	}
	if plan.PayloadReflected || plan.PayloadIntact {
		t.Fatalf("a block page must not be read as a reflection: %+v", plan)
	}
	if !strings.Contains(plan.Reason, "Cloudflare") || !strings.Contains(plan.Reason, "block") {
		t.Fatalf("reason does not explain the block: %q", plan.Reason)
	}
	want := []string{"html_case_variation", "html_alt_separator", "html_event_handler_details"}
	if got := wafAdaptiveTacticIDs(plan); !reflect.DeepEqual(got, want) {
		t.Fatalf("tactics = %v, want %v", got, want)
	}
	if plan.Tactics[0].Trigger != "waf_block" || plan.Tactics[0].Vector != adaptVectorHTML {
		t.Fatalf("unexpected provenance: %+v", plan.Tactics[0])
	}
	wafAdaptiveRequireSortedAndUnique(t, plan)
}

