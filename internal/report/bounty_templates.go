package report

// Platform-specific bug bounty submission Markdown renderers for HackerOne,
// Bugcrowd, and Intigriti. Like yeswehack.go, these render only confirmed
// findings in deterministic order, deduplicated by endpoint+parameter+payload,
// and fabricate nothing: CWE and CVSS v3.1 baseline vectors come from Classify,
// and PoC commands come from stored HTTP request evidence when available.

import (
	"fmt"
	"io"
	"strings"

	"github.com/indago/indago/internal/domain"
)

type bountyPlatformConfig struct {
	PlatformName   string
	WeaknessLabel  string
	IncludeVRTType bool
	AssetLabel     string
	SeverityLabel  string
	StepsHeading   string
	PoCHeading     string
}

var (
	hackerOneConfig = bountyPlatformConfig{
		PlatformName:  "HackerOne",
		WeaknessLabel: "Weakness",
		AssetLabel:    "Asset",
		SeverityLabel: "Severity",
		StepsHeading:  "## Steps To Reproduce",
		PoCHeading:    "## Proof of Concept",
	}
	bugcrowdConfig = bountyPlatformConfig{
		PlatformName:   "Bugcrowd",
		WeaknessLabel:  "VRT / Weakness",
		IncludeVRTType: true,
		AssetLabel:     "Target / Asset",
		SeverityLabel:  "Severity / CVSS",
		StepsHeading:   "## Steps to Reproduce",
		PoCHeading:     "## Proof of Concept (PoC)",
	}
	intigritiConfig = bountyPlatformConfig{
		PlatformName:  "Intigriti",
		WeaknessLabel: "Vulnerability Type",
		AssetLabel:    "Endpoint",
		SeverityLabel: "Severity",
		StepsHeading:  "## Steps to Reproduce",
		PoCHeading:    "## Proof of Concept",
	}
)

func writeHackerOneMarkdown(w io.Writer, data Data) error {
	return writeBountyPlatformMarkdown(w, data, hackerOneConfig)
}

func writeBugcrowdMarkdown(w io.Writer, data Data) error {
	return writeBountyPlatformMarkdown(w, data, bugcrowdConfig)
}

func writeIntigritiMarkdown(w io.Writer, data Data) error {
	return writeBountyPlatformMarkdown(w, data, intigritiConfig)
}

func writeBountyPlatformMarkdown(w io.Writer, data Data, cfg bountyPlatformConfig) error {
	findings := Prioritized(data.Findings)
	confirmed := make([]*domain.Finding, 0, len(findings))
	for _, f := range findings {
		if f.Verdict == domain.VerdictConfirmed {
			confirmed = append(confirmed, f)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s submission — %s\n\n", cfg.PlatformName, nonEmpty(data.Project.Name, "project"))
	fmt.Fprintf(&b, "_Generated by indago %s from scan `%s` (%s). One section per confirmed finding._\n\n",
		nonEmpty(data.ToolVersion, "dev"), data.Scan.ID, data.GeneratedAt.UTC().Format("2006-01-02T15:04:05Z"))

	if len(confirmed) == 0 {
		b.WriteString("No confirmed findings were recorded in the selected set — nothing to submit.\n")
		_, err := io.WriteString(w, b.String())
		return err
	}

	idx := EvidenceIndex(data.Evidence)
	seen := map[string]bool{}
	var omitted, n int
	for _, f := range confirmed {
		v := NewFindingViewWithRequests(f, idx, data.RequestEvidence)
		endpoint := nonEmpty(data.Endpoints[f.EndpointID], "—")
		payload := findingPayload(v)

		dedupKey := dedupEndpoint(endpoint) + "|" + v.ParamName + "|" + payload
		if seen[dedupKey] {
			omitted++
			continue
		}
		seen[dedupKey] = true
		n++
		if n > 1 {
			b.WriteString("\n---\n\n")
		}
		writeBountyFinding(&b, n, f, v, endpoint, payload, cfg)
	}
	if omitted > 0 {
		fmt.Fprintf(&b, "\n_%d duplicate finding(s) for the same endpoint/parameter/payload were omitted._\n", omitted)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func writeBountyFinding(b *strings.Builder, num int, f *domain.Finding, v FindingView, endpoint, payload string, cfg bountyPlatformConfig) {
	fmt.Fprintf(b, "# %d. %s\n\n", num, nonEmpty(f.Title, string(f.ID)))

	weakness := formatWeakness(f.VulnClass, v.Classification, cfg.IncludeVRTType)
	severity := formatSeverityCVSS(f.Severity, v.Classification)

	fmt.Fprintf(b, "**%s:** %s  \n", cfg.WeaknessLabel, weakness)
	fmt.Fprintf(b, "**%s:** %s  \n", cfg.AssetLabel, endpoint)
	fmt.Fprintf(b, "**%s:** %s  \n", cfg.SeverityLabel, severity)
	if v.ParamName != "" {
		fmt.Fprintf(b, "**Vulnerable parameter:** `%s`  \n", v.ParamName)
	}
	if payload != "" {
		fmt.Fprintf(b, "**Payload:** `%s`  \n", payload)
	}
	b.WriteString("\n")

	b.WriteString("## Summary\n\n")
	fmt.Fprintf(b, "%s\n\n", nonEmpty(f.Summary, f.Title))
	if v.Combined {
		fmt.Fprintf(b, "This finding required two parameters mutated in the same request: `%s` and `%s`.\n\n", v.ParamName, v.ParamNameB)
	}

	b.WriteString(cfg.StepsHeading + "\n\n")
	fmt.Fprintf(b, "1. Send a `%s` request to `%s`.\n", nonEmpty(v.Method, "GET"), endpoint)
	if v.ParamName != "" {
		fmt.Fprintf(b, "2. Inject the payload into the `%s` parameter:\n\n   ```\n   %s\n   ```\n\n", v.ParamName, payload)
	} else if payload != "" {
		fmt.Fprintf(b, "2. Inject the payload:\n\n   ```\n   %s\n   ```\n\n", payload)
	} else {
		b.WriteString("2. Replay the request against the target endpoint.\n\n")
	}
	if v.Verified != nil {
		fmt.Fprintf(b, "3. Observe the confirming verification signal: %s\n\n", nonEmpty(v.Verified.Notes, "the marker executed"))
	} else {
		b.WriteString("3. Observe the recorded execution signal in the captured evidence.\n\n")
	}

	b.WriteString(cfg.PoCHeading + "\n\n")
	if v.CurlPoC != nil && v.CurlPoC.Command != "" {
		b.WriteString("```bash\n")
		b.WriteString(v.CurlPoC.Command)
		if !strings.HasSuffix(v.CurlPoC.Command, "\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n\n")
		if v.CurlPoC.Note != "" {
			fmt.Fprintf(b, "_Note: %s_\n\n", v.CurlPoC.Note)
		}
	}
	b.WriteString("```http\n")
	fmt.Fprintf(b, "%s %s\n", nonEmpty(v.Method, "GET"), pocURL(endpoint, v, payload))
	b.WriteString("```\n\n")
	if len(v.Evidence) > 0 {
		b.WriteString("Evidence captured by the scanner:\n\n")
		for _, ev := range v.Evidence {
			fmt.Fprintf(b, "- `%s` — %s (%d bytes)\n", ev.ID, ev.Kind, ev.Size)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Impact\n\n")
	fmt.Fprintf(b, "%s\n\n", riskSentence(f.VulnClass))

	b.WriteString("## Remediation\n\n")
	fmt.Fprintf(b, "%s\n", ywhRemediation(f.VulnClass))
}

func findingPayload(v FindingView) string {
	if v.Verified != nil && v.Verified.CandidateValue != "" {
		return v.Verified.CandidateValue
	}
	if len(v.Candidates) > 0 {
		return v.Candidates[0].Value
	}
	return ""
}

func formatWeakness(class domain.VulnClass, c *Classification, includeVRT bool) string {
	cwe := "unclassified"
	if c != nil {
		cwe = c.CWE.String()
	}
	if includeVRT {
		return fmt.Sprintf("%s (%s)", ywhBugType(class), cwe)
	}
	return cwe
}

func formatSeverityCVSS(sev domain.Severity, c *Classification) string {
	label := titleCase(string(sev))
	if c == nil {
		return fmt.Sprintf("%s (CVSS: unclassified)", label)
	}
	return fmt.Sprintf("%s — %s (%s)", label, c.CVSS.String(), ClassificationNote)
}
