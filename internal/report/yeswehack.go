package report

// YesWeHack submission layout.
//
// The platform's own report editor offers a "YWH Report Template" tab that
// inserts a fixed Markdown skeleton — Description, Exploitation, PoC, Risk,
// Remediation — next to a form with separate fields (bug type, scope, endpoint,
// vulnerable part, part name, payload, technical environment, fingerprint, CVE,
// impact, IPs, CVSS 3.1). This renderer produces that skeleton from stored
// findings so a submission is a copy-paste, not a rewrite.
//
// It fabricates nothing: every field comes from the finding, its stored
// candidates/attempts or the endpoint map. CVSS is NOT computed — the scanner
// has a severity verdict, not a vector — so the line says so and the operator
// assigns the vector in the form.

import (
	"fmt"
	"io"
	"net/url"
	"strings"

	"github.com/indago/indago/internal/domain"
)

// ywhBugType maps Indago's classes to the wording the platform's bug-type
// picker uses.
func ywhBugType(c domain.VulnClass) string {
	switch c {
	case domain.VulnReflectedXSS, domain.VulnDOMXSS, domain.VulnStoredXSS:
		return "Cross-Site Scripting (XSS)"
	case domain.VulnIDOR:
		return "Broken Access Control (BAC) / IDOR"
	case domain.VulnAccessControl:
		return "Broken Access Control (BAC)"
	case domain.VulnInfoDisclosure:
		return "Information Disclosure"
	default:
		return string(c)
	}
}

// ywhRemediation is standard, class-level guidance — not a claim about the
// target's code.
func ywhRemediation(c domain.VulnClass) string {
	switch c {
	case domain.VulnReflectedXSS, domain.VulnDOMXSS, domain.VulnStoredXSS:
		return "Encode the value for the context it is written into (HTML text, attribute, JavaScript string, URL), and validate it against an allow-list. Prefer framework auto-escaping over hand-built markup, and keep a Content-Security-Policy that forbids inline script as defence in depth."
	case domain.VulnIDOR:
		return "Authorize every object access against the authenticated principal on the server, not by hiding identifiers. Use unguessable identifiers only as defence in depth, never as the authorization control."
	case domain.VulnAccessControl:
		return "Enforce the authorization check on the server for every administrative function and deny by default; do not rely on the route being unlinked or on client-side checks."
	case domain.VulnInfoDisclosure:
		return "Remove the exposed artefact from the web root, deny access to version-control and backup paths at the server, and rotate any credential the artefact contained."
	default:
		return "Apply the remediation appropriate to the vulnerability class and verify it with the same reproduction steps."
	}
}

func writeYesWeHackMarkdown(w io.Writer, data Data) error {
	findings := Prioritized(data.Findings)
	confirmed := make([]*domain.Finding, 0, len(findings))
	for _, f := range findings {
		if f.Verdict == domain.VerdictConfirmed {
			confirmed = append(confirmed, f)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# YesWeHack submission — %s\n\n", nonEmpty(data.Project.Name, "project"))
	fmt.Fprintf(&b, "_Generated by indago %s from scan `%s` (%s). One section per confirmed finding; the platform takes one report per finding._\n\n",
		nonEmpty(data.ToolVersion, "dev"), data.Scan.ID, data.GeneratedAt.UTC().Format("2006-01-02T15:04:05Z"))

	if len(confirmed) == 0 {
		b.WriteString("No confirmed findings were recorded in the selected set — nothing to submit.\n")
		_, err := io.WriteString(w, b.String())
		return err
	}

	idx := EvidenceIndex(data.Evidence)
	seen := map[string]bool{}
	var omitted, n int
	for _, f := range confirmed {
		v := NewFindingView(f, idx)
		endpoint := data.Endpoints[f.EndpointID]
		if endpoint == "" {
			endpoint = "—"
		}
		payload := ""
		if v.Verified != nil {
			payload = v.Verified.CandidateValue
		}
		if payload == "" && len(v.Candidates) > 0 {
			payload = v.Candidates[0].Value
		}
		// One submission per distinct finding: two rows for the same
		// endpoint+parameter+payload are the same bug and a triager closes
		// the duplicate.
		dedupKey := dedupEndpoint(endpoint) + "|" + v.ParamName + "|" + payload
		if seen[dedupKey] {
			omitted++
			continue
		}
		seen[dedupKey] = true
		n++
		if n > 1 {
			b.WriteString("\n---\n\n")
		}
		fmt.Fprintf(&b, "# %d. %s\n\n", n, f.Title)
		fmt.Fprintf(&b, "**Bug type:** %s  \n", ywhBugType(f.VulnClass))
		fmt.Fprintf(&b, "**Scope:** %s  \n", endpoint)
		fmt.Fprintf(&b, "**Endpoint:** %s  \n", endpoint)
		fmt.Fprintf(&b, "**Vulnerable part:** %s  \n", nonEmpty(string(f.Location), "—"))
		fmt.Fprintf(&b, "**Part name:** %s  \n", nonEmpty(v.ParamName, "—"))
		if payload != "" {
			fmt.Fprintf(&b, "**Payload:** `%s`  \n", payload)
		}
		fmt.Fprintf(&b, "**Technical environment:** indago %s, Chromium browser verification  \n", nonEmpty(data.ToolVersion, "dev"))
		b.WriteString("**Application fingerprint:** — (fill from the target's response headers)  \n")
		b.WriteString("**CVE:** —  \n")
		fmt.Fprintf(&b, "**Impact:** %s — %s  \n", titleCase(string(f.Severity)), riskSentence(f.VulnClass))
		b.WriteString("**CVSS:** not scored by Indago (severity is the engine's verdict, not a CVSS computation) — assign the 3.1 vector in the form  \n")
		b.WriteString("**IPs used:** — (add the egress IP you tested from)  \n\n")

		b.WriteString("## Description\n\n")
		fmt.Fprintf(&b, "%s\n\n", nonEmpty(f.Summary, f.Title))
		if v.Combined {
			fmt.Fprintf(&b, "This finding required two parameters mutated in the same request: `%s` and `%s`.\n\n", v.ParamName, v.ParamNameB)
		}

		b.WriteString("## Exploitation\n\n")
		fmt.Fprintf(&b, "1. Send a `%s` request to `%s`.\n", nonEmpty(v.Method, "GET"), endpoint)
		if v.ParamName != "" {
			fmt.Fprintf(&b, "2. Inject the payload into the `%s` parameter:\n\n   ```\n   %s\n   ```\n\n", v.ParamName, payload)
		} else {
			fmt.Fprintf(&b, "2. Inject the payload:\n\n   ```\n   %s\n   ```\n\n", payload)
		}
		if v.Verified != nil {
			fmt.Fprintf(&b, "3. The browser verification recorded the confirming signal: %s\n\n", nonEmpty(v.Verified.Notes, "the marker executed"))
		} else {
			b.WriteString("3. Observe the recorded execution signal in the captured evidence.\n\n")
		}

		b.WriteString("## PoC\n\n")
		b.WriteString("```http\n")
		fmt.Fprintf(&b, "%s %s\n", nonEmpty(v.Method, "GET"), pocURL(endpoint, v, payload))
		b.WriteString("```\n\n")
		if len(v.Evidence) > 0 {
			b.WriteString("Evidence captured by the scanner:\n\n")
			for _, ev := range v.Evidence {
				fmt.Fprintf(&b, "- `%s` — %s (%d bytes)\n", ev.ID, ev.Kind, ev.Size)
			}
			b.WriteString("\n")
		}

		b.WriteString("## Risk\n\n")
		fmt.Fprintf(&b, "Severity %s, confidence %s. %s\n\n", f.Severity, f.Confidence,
			riskSentence(f.VulnClass))

		b.WriteString("## Remediation\n\n")
		fmt.Fprintf(&b, "%s\n", ywhRemediation(f.VulnClass))
	}
	if omitted > 0 {
		fmt.Fprintf(&b, "\n_%d duplicate finding(s) for the same endpoint/parameter/payload were omitted._\n", omitted)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// riskSentence is a class-level consequence statement, not a claim about this
// target's data.
func riskSentence(c domain.VulnClass) string {
	switch c {
	case domain.VulnReflectedXSS, domain.VulnDOMXSS, domain.VulnStoredXSS:
		return "An attacker who controls the injected value can run script in a victim's session on this origin, with the actions and data that session can reach."
	case domain.VulnIDOR:
		return "An authenticated attacker can read or change another principal's object by changing an identifier, which is a confidentiality and integrity exposure."
	case domain.VulnAccessControl:
		return "A function that should require authorization is reachable without it, exposing administrative actions to an unprivileged caller."
	case domain.VulnInfoDisclosure:
		return "The exposed material can give an attacker configuration details or credentials that shorten the path to a deeper compromise."
	default:
		return "The impact follows from the vulnerability class and the data the affected surface can reach."
	}
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// pocURL is the request line a triager can replay. It prefers the URL the
// verifier actually navigated to (the candidate already substituted), and
// otherwise substitutes the payload into the query string for a GET.
func pocURL(endpoint string, v FindingView, payload string) string {
	if v.Verified != nil && v.Verified.URL != "" {
		return v.Verified.URL
	}
	if payload == "" || v.ParamName == "" {
		return endpoint
	}
	u, err := url.Parse(endpoint)
	if err != nil {
		return endpoint
	}
	q := u.Query()
	q.Set(v.ParamName, payload)
	u.RawQuery = q.Encode()
	return u.String()
}

// dedupEndpoint drops the query string: two findings that differ only in the
// test value are the same vulnerability on the same endpoint.
func dedupEndpoint(endpoint string) string {
	u, err := url.Parse(endpoint)
	if err != nil {
		return endpoint
	}
	return u.Scheme + "://" + u.Host + u.Path
}
